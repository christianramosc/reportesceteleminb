def _limpiar_moneda(serie):
    return (
        serie.astype(str)
             .str.replace(r"[\$,]", "", regex=True)
             .str.strip()
             .replace({"nan": np.nan, "": np.nan, "None": np.nan})
             .astype(float)
    )


def _limpiar_porcentaje(serie):
    """Convierte la columna de tasa de interés a número (ej. "14.99%" -> 14.99).

    OJO — esto es lo que estaba descuadrando la tasa de FINANCIADOS:
    en Excel una celda puede guardar "14.99%" como TEXTO, o como NÚMERO
    con formato de celda "0.00%" (en ese caso Excel guarda por dentro la
    fracción 0.1499, sin el símbolo %). Si sólo se le quita el "%" al
    texto, esas celdas numéricas se quedan en 0.1499 en vez de 14.99 y
    arruinan cualquier promedio. Por eso aquí se revisa el valor
    ORIGINAL de cada celda (no su versión ya convertida a texto) y, si
    es un número <= 1, se asume que viene en formato fracción de Excel
    y se multiplica x100.
    """
    def _convertir(valor):
        if pd.isna(valor):
            return np.nan
        if isinstance(valor, str):
            texto = valor.strip().replace("%", "")
            if texto in ("", "nan", "None"):
                return np.nan
            try:
                return float(texto)
            except ValueError:
                return np.nan
        try:
            numero = float(valor)
        except (TypeError, ValueError):
            return np.nan
        return numero * 100 if numero <= 1 else numero

    return serie.apply(_convertir)


def clasificar_status(status):
    s = str(status).strip().upper()
    if s in STATUS_FINANCIADO:
        return "FINANCIADO"
    if s in STATUS_APROBADO:
        return "APROBADO"
    if s in STATUS_RECHAZADOS:
        return "RECHAZADO"
    return "CONTRAPROPUESTA"


def limpiar_datos(df_original):
    df = df_original.copy()
    df.columns = [str(c).strip() for c in df.columns]

    faltantes = [c for c in COLUMNAS_ESPERADAS if c not in df.columns]
    if faltantes:
        print(f"Aviso: no se encontraron estas columnas esperadas: {faltantes}")
        print("El script seguirá, pero los análisis que dependan de ellas se omitirán.\n")

    for col in COLUMNAS_MONEDA:
        if col in df.columns:
            df[col] = _limpiar_moneda(df[col])

    for col in COLUMNAS_PORCENTAJE:
        if col in df.columns:
            crudo = df[col]
            df[col] = _limpiar_porcentaje(crudo)
            # Aviso de calidad de datos: celdas numéricas guardadas con
            # formato de porcentaje de Excel (fracción, ej. 0.1499) en vez
            # de texto "14.99%". El script ya las corrige automáticamente,
            # pero conviene saber cuáles filas venían así en el archivo fuente.
            es_formato_distinto = crudo.apply(
                lambda v: not isinstance(v, str) and pd.notna(v) and float(v) <= 1
            )
            if es_formato_distinto.any():
                idx = crudo[es_formato_distinto].index
                folios = (
                    df.loc[idx, "Folio CCK"].tolist() if "Folio CCK" in df.columns else list(idx)
                )
                print(
                    f"Aviso: {len(folios)} fila(s) en '{col}' tenían formato de celda "
                    f"distinto (número en vez de texto, ej. 0.1499 en vez de \"14.99%\") "
                    f"y se corrigieron automáticamente. Folios: {folios}"
                )

    if "STATUS" in df.columns:
        df["STATUS"] = df["STATUS"].astype(str).str.strip().str.upper()
        df["Categoria"] = df["STATUS"].apply(clasificar_status)

    if "Nombre del Vendedor" in df.columns:
        df["Nombre del Vendedor"] = (
            df["Nombre del Vendedor"].astype(str).str.strip().str.title()
        )

    if "Marca" in df.columns:
        df["Marca"] = df["Marca"].astype(str).str.strip().str.upper().replace("NAN", np.nan)

    if "Vehículo" in df.columns:
        df["Vehículo"] = df["Vehículo"].astype(str).str.strip().replace("None", np.nan)

    if "Fecha de Nacimiento" in df.columns:
        df["Fecha de Nacimiento"] = pd.to_datetime(
            df["Fecha de Nacimiento"], dayfirst=True, errors="coerce"
        )
        hoy = pd.Timestamp.today()
        df["Edad"] = ((hoy - df["Fecha de Nacimiento"]).dt.days // 365.25)

    if "¿Tiene GAP?" in df.columns:
        df["¿Tiene GAP?"] = df["¿Tiene GAP?"].astype(str).str.strip().str.upper()

    return df


