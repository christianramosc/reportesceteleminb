    print(" RESUMEN GENERAL DEL PERIODO")
    print("=" * 72)

    total = len(df)
    r = {"total": total}
    print(f"Total de solicitudes ingresadas: {total}\n")

    if "Categoria" in df.columns:
        conteo_cat  = df["Categoria"].value_counts()
        financiados = int(conteo_cat.get("FINANCIADO", 0))
        aprobados   = int(conteo_cat.get("APROBADO", 0))
        rechazados  = int(conteo_cat.get("RECHAZADO", 0))
        en_tramite  = int(conteo_cat.get("CONTRAPROPUESTA", 0))

        print(f"  Financiadas (crédito dispersado) : {financiados:>3}  ({financiados/total*100:5.1f}%)")
        print(f"  Aprobadas (aún sin dispersar)    : {aprobados:>3}  ({aprobados/total*100:5.1f}%)")
        print(f"  Rechazadas                       : {rechazados:>3}  ({rechazados/total*100:5.1f}%)")
        print(f"  CONTRAPROPUESTA / negociación         : {en_tramite:>3}  ({en_tramite/total*100:5.1f}%) ")

        print("\nDesglose detallado por Estatus:")
        for status, cnt in df["STATUS"].value_counts().items():
            print(f"    - {status:<20}: {cnt:>3}  ({cnt/total*100:5.1f}%) ")

        r.update({
            "financiados": financiados, "aprobados": aprobados,
            "rechazados": rechazados, "en_tramite": en_tramite,
            "desglose_status": df["STATUS"].value_counts(),
        })
    else:
        financiados = aprobados = rechazados = en_tramite = 0

    monto_col = "Monto Total a Financiar"
    if monto_col in df.columns:
        monto_total = df[monto_col].sum()
        r["monto_total"] = monto_total
        print(f"\nMonto total a financiar (TODAS las solicitudes)  : ${monto_total:,.2f}")

        if "Categoria" in df.columns:
            monto_financiado = df.loc[df["Categoria"] == "FINANCIADO", monto_col].sum()
            monto_aprobado   = df.loc[df["Categoria"] == "APROBADO", monto_col].sum()
            r["monto_financiado"] = monto_financiado
            r["monto_aprobado"] = monto_aprobado

            print(f"Monto FINANCIADO (crédito ya dispersado)          : ${monto_financiado:,.2f}")
            if financiados:
                ticket_financiado = df.loc[df["Categoria"] == "FINANCIADO", monto_col].mean()
                r["ticket_financiado"] = ticket_financiado
                print(f"  Ticket promedio financiadas                     : ${ticket_financiado:,.2f}")

            print(f"Monto APROBADO (aún sin dispersar)                : ${monto_aprobado:,.2f}")
            if aprobados:
                ticket_aprobado = df.loc[df["Categoria"] == "APROBADO", monto_col].mean()
                r["ticket_aprobado"] = ticket_aprobado
                print(f"  Ticket promedio aprobadas                       : ${ticket_aprobado:,.2f}")

