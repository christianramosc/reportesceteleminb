def _quienes_maximo(serie):
    """Devuelve (lista_de_nombres, valor_maximo) para una Series indexada por
    vendedor. Si hay empate en el máximo, regresa a TODOS los empatados.
    Si la serie está vacía o el máximo es 0/():  regresa ([], 0)."""
    if serie is None or serie.empty:
        return [], 0
    maximo = serie.max()
    if pd.isna(maximo) or maximo <= 0:
        return [], 0
    nombres = serie[serie == maximo].index.tolist()
    return nombres, maximo


def _nombres_y(nombres):
    """Une una lista de nombres en texto natural: 'A', 'A y B', 'A, B y C'."""
    nombres = [str(n) for n in nombres]
    if not nombres:
        return ""
    if len(nombres) == 1:
        return nombres[0]
    return ", ".join(nombres[:-1]) + " y " + nombres[-1]


def imagen_ajustada(ruta, ancho_cm, alto_max_cm=None):
    """Crea un flowable Image respetando la proporción real del PNG, para
    que las gráficas horizontales (con alturas variables según el número
    de vendedores o modelos) siempre se vean bien en el PDF."""
    ancho_px, alto_px = ImageReader(ruta).getSize()
    alto_cm = ancho_cm * (alto_px / ancho_px)
    if alto_max_cm and alto_cm > alto_max_cm:
        alto_cm = alto_max_cm
        ancho_cm = alto_cm * (ancho_px / alto_px)
    return Image(ruta, width=ancho_cm * cm, height=alto_cm * cm, hAlign="CENTER")


