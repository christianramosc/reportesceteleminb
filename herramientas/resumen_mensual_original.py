def _lista_vendedores_por_categoria(df, categoria, max_nombres=4):
    """Devuelve un string compacto con los primeros nombres de los
    vendedores que tienen solicitudes en esa categoría (para no saturar
    la leyenda con nombres completos)."""
    nombres = (
        df.loc[df["Categoria"] == categoria, "Nombre del Vendedor"]
        .dropna().unique().tolist()
    )
    primeros_nombres = sorted({n.split()[0] for n in nombres if n and n != "Nan"})
    if not primeros_nombres:
        return "—"
    if len(primeros_nombres) > max_nombres:
        extra = len(primeros_nombres) - max_nombres
        return ", ".join(primeros_nombres[:max_nombres]) + f" +{extra} más"
    return ", ".join(primeros_nombres)


