def resumen_general(df):
    print("=" * 72)
    print(" RESUMEN GENERAL DEL PERIODO")
    print("=" * 72)

    total = len(df)
    r = {"total": total}
    print(f"Total de solicitudes ingresadas: {total}\n")

    if "Categoria" in df.columns:
        conteo_cat = df["Categoria"].value_counts()

        # Conteo de TODAS las categorías presentes, no solo de las cuatro
        # que antes estaban escritas a mano.
        conteo_categorias = {
            c: int(conteo_cat.get(c, 0)) for c in _est.categorias_presentes(df)
        }

        financiados = int(conteo_cat.get("FINANCIADO", 0))
        aprobados   = int(conteo_cat.get("APROBADO", 0))
        rechazados  = int(conteo_cat.get("RECHAZADO", 0))

        # "en_tramite" = todo lo que sigue vivo y todavía puede convertirse
        # en financiado, EXCEPTO lo ya aprobado (que se reporta aparte):
        # contrapropuesta, en proceso, en revisión, pendiente, etc.
        claves_abiertas = [c for c in _est.claves_por_grupo(_est.ABIERTA)
                           if c != "APROBADO"]
        en_tramite = sum(int(conteo_cat.get(c, 0)) for c in claves_abiertas)

        for clave, cnt in conteo_categorias.items():
            print(f"  {_est.etiqueta(clave):<24}: {cnt:>3}  ({cnt/total*100:5.1f}%)")

        print("\nDesglose detallado por ESTATUS (texto tal cual del Excel):")
        for status, cnt in df["STATUS"].value_counts().items():
            print(f"    - {status:<20}: {cnt:>3}  ({cnt/total*100:5.1f}%) ")

        r.update({
            "financiados": financiados, "aprobados": aprobados,
            "rechazados": rechazados, "en_tramite": en_tramite,
            "conteo_categorias": conteo_categorias,
            "claves_abiertas": claves_abiertas,
            "desglose_status": df["STATUS"].value_counts(),
        })
    else:
        financiados = aprobados = rechazados = en_tramite = 0

    monto_col = "Monto Total a Financiar"
    if monto_col in df.columns:
        monto_total = df[monto_col].sum()
        r["monto_total"] = monto_total
        print(f"\nMonto total a financiar (TODAS las solicitudes)  : ${monto_total:,.2f}")

        if "Categoria" in df.columns:
            monto_financiado = df.loc[df["Categoria"] == "FINANCIADO", monto_col].sum()
            monto_aprobado   = df.loc[df["Categoria"] == "APROBADO", monto_col].sum()
            r["monto_financiado"] = monto_financiado
            r["monto_aprobado"] = monto_aprobado

            print(f"Monto FINANCIADO (crédito ya dispersado)          : ${monto_financiado:,.2f}")
            if financiados:
                ticket_financiado = df.loc[df["Categoria"] == "FINANCIADO", monto_col].mean()
                r["ticket_financiado"] = ticket_financiado
                print(f"  Ticket promedio financiadas                     : ${ticket_financiado:,.2f}")

            print(f"Monto APROBADO (aún sin dispersar)                : ${monto_aprobado:,.2f}")
            if aprobados:
                ticket_aprobado = df.loc[df["Categoria"] == "APROBADO", monto_col].mean()
                r["ticket_aprobado"] = ticket_aprobado
                print(f"  Ticket promedio aprobadas                       : ${ticket_aprobado:,.2f}")

            print(f"Monto conjunto (Aprobado + Financiado)            : ${monto_financiado + monto_aprobado:,.2f}")

    if "Enganche" in df.columns and "Precio Venta (c/IVA)" in df.columns:
        pct_enganche = (df["Enganche"] / df["Precio Venta (c/IVA)"] * 100).mean()
        r["pct_enganche"] = pct_enganche
        print(f"\n% de enganche promedio sobre precio de venta      : {pct_enganche:.1f}%")

    if "Plazo (meses)" in df.columns:
        r["plazo_promedio"] = df["Plazo (meses)"].mean()
        print(f"Plazo promedio solicitado                         : {df['Plazo (meses)'].mean():.0f} meses")

    if "Tasa Interés Anual" in df.columns:
        r["tasa_promedio"] = df["Tasa Interés Anual"].mean()
        print(f"Tasa de interés anual promedio                    : {df['Tasa Interés Anual'].mean():.2f}%")

    if "¿Tiene GAP?" in df.columns:
        pct_gap = (df["¿Tiene GAP?"] == "SI").mean() * 100
        r["pct_gap"] = pct_gap
        r["n_gap"] = int((df["¿Tiene GAP?"] == "SI").sum())
        print(f"% de solicitudes con GAP                          : {pct_gap:.1f}%")

    if "Edad" in df.columns and df["Edad"].notna().any():
        r["edad_promedio"] = df["Edad"].mean()

    # filas con datos incompletos (p.ej. folio sin vehículo asignado aún)
    cols_clave = [c for c in ["Marca", "Vehículo", "Monto Total a Financiar"] if c in df.columns]
    if cols_clave:
        incompletas = df[cols_clave].isna().any(axis=1).sum()
        r["incompletas"] = int(incompletas)
        if incompletas:
            print(f"\nSolicitudes con datos incompletos (vehículo/monto sin capturar): {incompletas}")

    print()
    return r


