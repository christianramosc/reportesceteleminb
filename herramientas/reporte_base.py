    print("\nEsta tabla ayuda a identificar focos de atención: por ejemplo, si las")
    print("solicitudes RECHAZADAS piden un % de enganche más bajo, un monto a")
    print("financiar más alto, o llevan menos GAP que las APROBADAS o FINANCIADAS,")
    print("ese es un patrón a vigilar.\n")
