def contexto_de_corte(fecha_corte=None):
    """
    Ubica la fecha de corte del avance dentro del calendario del mes:
    en qué día se está cortando, cuántos días tiene el mes y qué % del
    mes ya transcurrió. Es solo contexto de calendario -no una meta ni
    una proyección de cierre-, para que el reporte deje claro qué tan
    "preliminares" son los resultados que muestra.

    Si no se indica fecha_corte, usa la fecha de hoy. También acepta un
    string ("15/08/2026") o un date/datetime ya construido.
    """
    if fecha_corte is None:
        fecha_corte = datetime.date.today()
    elif isinstance(fecha_corte, str):
        fecha_corte = pd.to_datetime(fecha_corte, dayfirst=True).date()
    elif isinstance(fecha_corte, datetime.datetime):
        fecha_corte = fecha_corte.date()

    dias_en_mes = calendar.monthrange(fecha_corte.year, fecha_corte.month)[1]
    dia_actual = fecha_corte.day
    dias_restantes = dias_en_mes - dia_actual

    return {
        "fecha_corte": fecha_corte,
        "nombre_mes": _MESES_ES[fecha_corte.month - 1],
        "dia_actual": dia_actual,
        "dias_en_mes": dias_en_mes,
        "pct_transcurrido": dia_actual / dias_en_mes * 100,
        "dias_restantes": dias_restantes,
    }


def _gradiente(n):
    """Genera n colores en degradado continuo (oscuro -> claro) sin repetirse,
    sin importar cuántas barras haya."""
    if n <= 1:
        return [MG_ROJO]
    valores = np.linspace(0.0, 0.82, n)
    return [_CMAP_ROJOS(v) for v in valores]


def _color_texto_legible(color_fondo):
    """Devuelve blanco o gris oscuro según qué tan claro sea el color de fondo,
    para que el texto siempre se pueda leer."""
    r, g, b = to_rgb(color_fondo)
    luminancia = 0.299 * r + 0.587 * g + 0.114 * b
    return "white" if luminancia < 0.6 else MG_GRIS_OSCURO


