def _limpiar_moneda(serie):
    return (
        serie.astype(str)
             .str.replace(r"[\$,]", "", regex=True)
             .str.strip()
             .replace({"nan": np.nan, "": np.nan, "None": np.nan})
             .astype(float)
    )


def _limpiar_porcentaje(serie):
    """Convierte la columna de tasa de interés a número (ej. "14.99%" -> 14.99).

    OJO — esto es lo que estaba descuadrando la tasa de FINANCIADOS:
    en Excel una celda puede guardar "14.99%" como TEXTO, o como NÚMERO
    con formato de celda "0.00%" (en ese caso Excel guarda por dentro la
    fracción 0.1499, sin el símbolo %). Si sólo se le quita el "%" al
    texto, esas celdas numéricas se quedan en 0.1499 en vez de 14.99 y
    arruinan cualquier promedio. Por eso aquí se revisa el valor
    ORIGINAL de cada celda (no su versión ya convertida a texto) y, si
    es un número <= 1, se asume que viene en formato fracción de Excel
    y se multiplica x100.
    """
    def _convertir(valor):
        if pd.isna(valor):
            return np.nan
        if isinstance(valor, str):
            texto = valor.strip().replace("%", "")
            if texto in ("", "nan", "None"):
                return np.nan
            try:
                return float(texto)
            except ValueError:
                return np.nan
        try:
            numero = float(valor)
        except (TypeError, ValueError):
            return np.nan
        return numero * 100 if numero <= 1 else numero

    return serie.apply(_convertir)


